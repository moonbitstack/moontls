"""Write tls/fixtures_test.mbt: a root, server certificates under four key types, their keys.

Issued by Python's `cryptography` (OpenSSL); rerun after changing a fixture.
"""

import datetime as dt
import pathlib
import sys

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, rsa
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

OUT = pathlib.Path(__file__).resolve().parent.parent / "tls" / "fixtures_test.mbt"
START = dt.datetime(2020, 1, 1, tzinfo=dt.timezone.utc)
END = dt.datetime(2040, 1, 1, tzinfo=dt.timezone.utc)


def name(cn):
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def cert(cn, key, issuer=None, ca=False):
    issuer_cert, issuer_key = issuer if issuer else (None, key)
    b = (x509.CertificateBuilder()
         .subject_name(name(cn))
         .issuer_name(issuer_cert.subject if issuer_cert else name(cn))
         .public_key(key.public_key())
         .serial_number(x509.random_serial_number())
         .not_valid_before(START)
         .not_valid_after(END))
    if ca:
        b = b.add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
    else:
        b = b.add_extension(x509.SubjectAlternativeName([x509.DNSName("a.example")]), critical=False)
        b = b.add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False)
    return b.sign(issuer_key, hashes.SHA256()), key


def pem(c):
    return c.public_bytes(serialization.Encoding.PEM).decode().strip()


def hexint(n, size):
    return n.to_bytes(size, "big").hex()


def main():
    root = cert("tls root", ec.generate_private_key(ec.SECP256R1()), ca=True)
    p256 = cert("p256", ec.generate_private_key(ec.SECP256R1()), root)
    p384 = cert("p384", ec.generate_private_key(ec.SECP384R1()), root)
    rk = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    rsa_leaf = cert("rsa", rk, root)
    ed = cert("ed", ed25519.Ed25519PrivateKey.generate(), root)
    other = cert("other root", ec.generate_private_key(ec.SECP256R1()), ca=True)

    rn = rk.private_numbers()
    values = {
        "root": pem(root[0]),
        "other_root": pem(other[0]),
        "p256_leaf": pem(p256[0]),
        "p384_leaf": pem(p384[0]),
        "rsa_leaf": pem(rsa_leaf[0]),
        "ed_leaf": pem(ed[0]),
        "p256_key": hexint(p256[1].private_numbers().private_value, 32),
        "p384_key": hexint(p384[1].private_numbers().private_value, 48),
        "rsa_n": hexint(rn.public_numbers.n, 256),
        "rsa_e": hexint(rn.public_numbers.e, 3),
        "rsa_d": hexint(rn.d, 256),
        "ed_key": ed[1].private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                                      serialization.NoEncryption()).hex(),
    }
    out = ["// Generated by scripts/gen_tls.py; rerun it rather than editing.", ""]
    for k, v in values.items():
        out.append("///|")
        if "\n" in v:
            out.append(f"let {k} : String =")
            out.extend("  #|" + line for line in v.split("\n"))
        else:
            out.append(f'let {k} : String = "{v}"')
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {len(values)} values to {OUT}")
    if len(sys.argv) > 1:
        pki = pathlib.Path(sys.argv[1])
        pki.mkdir(parents=True, exist_ok=True)
        pairs = {"root": root, "p256": p256, "p384": p384, "rsa": rsa_leaf, "ed": ed}
        for label, (c, k) in pairs.items():
            (pki / f"{label}.pem").write_text(pem(c) + "\n")
            (pki / f"{label}.key").write_bytes(k.private_bytes(
                serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                serialization.NoEncryption()))


if __name__ == "__main__":
    main()
