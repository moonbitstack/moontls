"""Write src/tls/client_fixtures_test.mbt: the anchors and certificates client authentication tests use.

Issued by Python's `cryptography` (OpenSSL); rerun after changing a fixture. The values are
deliberately unlike the server fixtures in `fixtures_test.mbt`: a client chain is a separate trust
domain, and a test that mixed the two would not notice a server accepting its own anchors.
"""

import datetime as dt
import pathlib

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "tls" / "client_fixtures_test.mbt"
START = dt.datetime(2020, 1, 1, tzinfo=dt.timezone.utc)
END = dt.datetime(2040, 1, 1, tzinfo=dt.timezone.utc)


def name(cn):
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def cert(cn, key, issuer=None, ca=False, client=True):
    issuer_cert, issuer_key = issuer if issuer else (None, key)
    b = (x509.CertificateBuilder()
         .subject_name(name(cn))
         .issuer_name(issuer_cert.subject if issuer_cert else name(cn))
         .public_key(key.public_key())
         .serial_number(x509.random_serial_number())
         .not_valid_before(START)
         .not_valid_after(END))
    if ca:
        b = b.add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
    else:
        usage = (ExtendedKeyUsageOID.CLIENT_AUTH if client
                 else ExtendedKeyUsageOID.SERVER_AUTH)
        b = b.add_extension(x509.ExtendedKeyUsage([usage]), critical=False)
    return b.sign(issuer_key, hashes.SHA256()), key


def pem(c):
    return c.public_bytes(serialization.Encoding.PEM).decode().strip()


def key_pem(k):
    return k.private_bytes(serialization.Encoding.PEM,
                           serialization.PrivateFormat.PKCS8,
                           serialization.NoEncryption()).decode().strip()


def main():
    root = cert("client root", ec.generate_private_key(ec.SECP256R1()), ca=True)
    leaf = cert("client", ec.generate_private_key(ec.SECP256R1()), root)
    rsa_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    rsa_leaf = cert("client rsa", rsa_key, root)
    wrong = cert("client for servers", ec.generate_private_key(ec.SECP256R1()), root,
                 client=False)
    other = cert("other client root", ec.generate_private_key(ec.SECP256R1()), ca=True)
    stranger = cert("stranger", ec.generate_private_key(ec.SECP256R1()), other)

    values = {
        "client_root": pem(root[0]),
        "client_leaf": pem(leaf[0]),
        "client_key": key_pem(leaf[1]),
        "client_rsa_leaf": pem(rsa_leaf[0]),
        "client_rsa_key": key_pem(rsa_leaf[1]),
        "client_server_leaf": pem(wrong[0]),
        "client_server_key": key_pem(wrong[1]),
        "stranger_root": pem(other[0]),
        "stranger_leaf": pem(stranger[0]),
        "stranger_key": key_pem(stranger[1]),
    }
    out = ["// Generated by scripts/gen_client_cert.py; rerun it rather than editing.", ""]
    for k, v in values.items():
        out.append("///|")
        out.append(f"let {k} : String =")
        out.extend("  #|" + line for line in v.split("\n"))
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {len(values)} values to {OUT}")


if __name__ == "__main__":
    main()
